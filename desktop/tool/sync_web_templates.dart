import 'dart:convert';
import 'dart:io';

/// Generate the desktop catalog from the web editor's actual template options.
/// This also runs before flutter_assemble during a Windows build.
void main() {
  final project = File.fromUri(Platform.script).parent.parent;
  final source = File(
    '${project.parent.path}/web/public/embedded/heart-star/index.html',
  );
  final html = source.readAsStringSync();
  final select = RegExp(
    r'<select\b[^>]*\bid="template"[^>]*>(.*?)</select>',
    dotAll: true,
  ).firstMatch(html)?.group(1);
  if (select == null) throw const FormatException('找不到 web 模板列表');
  final entries = RegExp(r'<option value="([^"]+)">([^<]+)</option>')
      .allMatches(select)
      .where((entry) => entry.group(1) != '自定义排版.png')
      .map((entry) => (id: entry.group(1)!, name: entry.group(2)!))
      .toList();
  if (entries.isEmpty ||
      entries.map((entry) => entry.id).toSet().length != entries.length) {
    throw const FormatException('web 模板列表为空或存在重复编号');
  }
  String literal(String value) => jsonEncode(value).replaceAll(r'$', r'\$');
  final generated =
      '''// Generated by tool/sync_web_templates.dart from the web editor. Do not edit.
part of 'template_definition.dart';

const webTemplates = <TemplateDefinition>[
${entries.map((entry) => '  TemplateDefinition(id: ${literal(entry.id)}, name: ${literal(entry.name)}),').join('\n')}
];
''';
  final output = File(
    '${project.path}/lib/features/templates/web_templates.g.dart',
  );
  if (!output.existsSync() || output.readAsStringSync() != generated) {
    output.writeAsStringSync(generated);
  }
}
